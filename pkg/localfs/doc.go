// Package localfs 是 momoko 唯一的本地文件管理包：所有对本机磁盘的读写都应经由此包，
// 由它统一承担「路径穿越防护 + 文件安全策略」，业务层只描述意图、不再自己拼路径。
//
// # 安全模型
//
// 本包不依赖字符串比较来防穿越，而是把每次操作都下沉到 os.Root（Go 1.24+）执行。
// os.Root 由内核层面的 openat/O_NOFOLLOW 语义保证「句柄永不逃出根目录」，因此天然免疫：
//
//   - "..": 相对上跳（含正反斜杠混用、多级嵌套）
//   - 绝对路径与盘符注入："/etc/passwd"、"C:\Windows"、"\\?\C:\..."、UNC "\\host\share"
//   - 符号链接 / Windows junction（目录重解析点）逃逸，且不存在 TOCTOU 竞态窗口
//   - Windows 备用数据流（"a.txt:evil"、"a.txt::$DATA"）与保留设备名（NUL/CON/COM1…）
//
// 字符串层面的规整（Clean、分隔符统一、mount 拆分）只服务于易用性与错误提示；
// 即便这些逻辑存在缺陷，也只可能造成「误拒」，绝不可能造成「误放行」。安全边界始终是 os.Root。
//
// os.Root 覆盖不到的两类问题由本包显式补齐：
//
//   - 名称合法性：Windows 会静默吞掉结尾的点与空格（写入 "a.txt " 实际落在 "a.txt"），
//     从而绕过 O_EXCL 存在性检查；另有控制字符、NUL 字节、超长名等。见 ValidateName。
//   - 资源型攻击：zip 炸弹（解压体积/条目数/压缩比）、全盘递归搜索导致的 CPU/内存耗尽。
//     见 Policy 中的各项上限。
//
// # 两种视图
//
// [Open] 返回锁死在某个目录内的受限视图，用于实例工作目录、分享条目、头像、生图存储等
// 一切「只应看见自己那一块」的场景。越界一律失败。
//
// [OpenSystem] 返回整机视图，供管理员文件管理器使用：Windows 下以盘符为挂载点
// （空路径即「此电脑」虚拟根），类 Unix 下挂载点为 "/"。整机视图仍然是若干 os.Root 之和，
// 因此穿越防护同样生效；对 momoko 自身敏感目录的保护由 Policy.Deny 承担。
//
// # 路径约定
//
// 入参（vpath）接受相对路径或本视图内的真实绝对路径，正反斜杠均可；含 ".." 段一律直接拒绝
// （显式报错而非静默规整，便于审计）。出参 Entry.Path 一律为真实绝对路径，可直接回传复用。
//
// 本包只依赖标准库：不引入 protobuf、不引入 ent、不引入任何 momoko internal 包，
// 以便被 pkg 与 internal 双向复用并可独立测试。
